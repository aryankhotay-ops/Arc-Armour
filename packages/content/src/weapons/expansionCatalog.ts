const slug = (name: string): string =>
  name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');

const make = (entry: ExpansionEntry, pack: WeaponPackId): WeaponDefinition => {
  const accent = entry.color ?? PACK_COLOR[pack] ?? 0xffcb70;
  return Object.freeze<WeaponDefinition>({
    id: slug(entry.n),
    name: entry.n,
    pack,
    role: entry.r,
    description: entry.d,
    adaptationNote:
      entry.note ??
      'HP-based arcade adaptation of the referenced depot weapon. Original visuals and bounded effects, not Pocket Tanks scoring or pixel-exact physics.',
    icon: entry.i,
    accent,
    ammo: entry.ammo ?? 3,
    launch: {
      projectileCount: entry.count ?? 1,
      spreadDegrees: entry.spread ?? 0,
      speed: entry.speed ?? SPEED,
    },
    projectile: { radius: 5, gravityScale: 1, windScale: 1, maxLifetimeSeconds: 16, ...entry.p },
    explosion: { blastRadius: 58, terrainRadius: 44, maxDamage: 30, directHitBonus: 6, ...entry.e },
    trail: {
      style: entry.i === 'rail' ? 'glow' : entry.i === 'cluster' ? 'spark' : 'smoke',
      color: accent,
      width: entry.i === 'rail' ? 2 : 3,
      lifetimeSeconds: 0.55,
    },
    damageCapPerShot: entry.cap ?? 34,
  });
};

export const EXPANSION_PACK_NAMES: readonly WeaponPackId[] = PACKS.map(([pack]) => pack);

export const EXPANSION_CATALOG: readonly WeaponDefinition[] = Object.freeze(
  PACKS.flatMap(([pack, entries]) => entries.map((entry) => make(entry, pack))),
);
