/* global process, document, console */
import { chromium } from '@playwright/test';
const out = process.argv[2] ?? '/tmp/aa-shots';
const tag = process.argv[3] ?? 'shot';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
await page.goto('http://127.0.0.1:5199/?draft=on&seed=7');
await page.waitForSelector('body[data-scene=draft]');
await page.waitForTimeout(600);
await page.screenshot({ path: `${out}/${tag}-draft.png` });
await page.goto('http://127.0.0.1:5199/?draft=off');
await page.waitForSelector('body[data-scene=battlefield]');
await page.waitForTimeout(900);
await page.screenshot({ path: `${out}/${tag}-battle.png` });
await page.keyboard.press('Space');
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/${tag}-flight.png` });
await page.waitForFunction(() => document.body.dataset.eventCounts?.includes('explosion'), null, { timeout: 15000 });
await page.waitForTimeout(90);
await page.screenshot({ path: `${out}/${tag}-boom.png` });
await page.waitForTimeout(400);
await page.screenshot({ path: `${out}/${tag}-boom2.png` });
await page.waitForSelector('body[data-turn="2"]', { timeout: 15000 });
await page.waitForTimeout(700);
await page.screenshot({ path: `${out}/${tag}-after.png` });
console.log('errors:', JSON.stringify(errors));
await browser.close();
